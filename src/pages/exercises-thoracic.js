function renderInstruction(label, text, className = '') {
  return `
    <div class="neck-exercise-instruction ${className}">
      <span class="neck-exercise-instruction-label">${label}</span>
      <p>${text.trim()}</p>
    </div>
  `
}

function renderExercise(exercise) {
  const imagePath = `/images/exercises/thoracic/${exercise.image}`

  return `
    <section class="neck-exercise">
      <h3>
        <span class="neck-exercise-number">${exercise.number}</span>
        ${exercise.title}
      </h3>

      <figure class="neck-exercise-figure">
        <img
            src="${imagePath}"
            alt="${exercise.alt}"
            loading="lazy"
            draggable="false"
        />
      </figure>

      <div class="neck-exercise-instructions">
        ${renderInstruction('Вихідне положення', exercise.startingPosition)}
        ${renderInstruction('Виконання', exercise.execution)}
        ${renderInstruction('Уявляємо', exercise.imagine, 'is-imagine')}
        ${renderInstruction('ОМВ', exercise.omv, 'is-omv')}
      </div>
    </section>
  `
}

function renderVideoBlock() {
  if (!YOUTUBE_VIDEO_ID.trim()) {
    return ''
  }

  return `
    <section class="article-content-section neck-exercises-video">
      <h2>Відео виконання комплексу</h2>

      <div class="neck-video-frame">
        <iframe
          src="https://www.youtube-nocookie.com/embed/${YOUTUBE_VIDEO_ID}"
          title="Комплекс вправ для грудного відділу хребта"
          loading="lazy"
          allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
          referrerpolicy="strict-origin-when-cross-origin"
          allowfullscreen
        ></iframe>
      </div>
    </section>
  `
}

