// Формує блок інструкції.
// Якщо текст порожній або містить лише пробіли — блок не створюється.
function renderInstruction(label, text, className = '') {
  const content = typeof text === 'string' ? text.trim() : ''

  if (!content) {
    return ''
  }

  return `
    <div class="neck-exercise-instruction ${className}">
      <span class="neck-exercise-instruction-label">${label}</span>
      <p>${content}</p>
    </div>
  `
}

function renderExercise(exercise) {
  const imagePath = `/images/exercises/neck_potocki/${exercise.image}`

  const instructions = [
    renderInstruction('Вихідне положення:', exercise.startingPosition),
    renderInstruction('Виконання:', exercise.execution),
    renderInstruction('Уявляємо:', exercise.imagine, 'is-imagine'),
    renderInstruction('ОМВ:', exercise.omv, 'is-omv'),
    renderInstruction('Дотяг:', exercise.stretch, 'is-stretch'),
  ].join('')

  return `
    <section class="neck-exercise">
      <h3>
        <span class="neck-exercise-number">${exercise.number}</span>
        ${exercise.title}
      </h3>

      <figure class="neck-exercise-figure">
        <a
          href="${imagePath}"
          target="_blank"
          rel="noopener noreferrer"
          aria-label="Відкрити зображення: ${exercise.title}"
        >
          <img
            src="${imagePath}"
            alt="${exercise.alt}"
            loading="lazy"
          />
        </a>
      </figure>

      <div class="neck-exercise-instructions">
        ${instructions}
      </div>
    </section>
  `
}

