function renderInstruction(label, text, className = '') {
  return `
    <div class="neck-exercise-instruction ${className}">
      <strong>${label}</strong>
      <p>${text}</p>
    </div>
  `
}

function renderExercise(exercise) {
  return `
    <section class="neck-exercise">
      <h3>
        <span class="neck-exercise-number">${exercise.number}</span>
        ${exercise.title}
      </h3>

      <figure class="neck-exercise-figure">
        <img
          src="/images/exercises/${exercise.image}"
          alt="${exercise.alt}"
          loading="lazy"
        >
      </figure>

      <div class="neck-exercise-instructions">
        ${renderInstruction('Вихідне положення', exercise.startingPosition)}
        ${renderInstruction('Виконання', exercise.execution)}
        ${renderInstruction('Уявляємо', exercise.imagine)}
        ${renderInstruction('ОМВ', exercise.omv)}
        ${renderInstruction('Дотяг', exercise.stretch)}
      </div>
    </section>
  `
}

function renderVideoBlock() {
  if (!YOUTUBE_VIDEO_ID) return ''

  return `
    <section class="neck-exercise-video">
      <h2>Відео з комплексом вправ</h2>
      <div class="neck-exercise-video-frame">
        <iframe
          src="https://www.youtube-nocookie.com/embed/${YOUTUBE_VIDEO_ID}"
          title="Комплекс вправ для грудного відділу хребта"
          allowfullscreen
          loading="lazy"
        ></iframe>
      </div>
    </section>
  `
}

